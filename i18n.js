    const SKIP = '[data-i18n-skip]';
    const ATTRS = ['alt', 'placeholder', 'aria-label', 'title'];
    const textOriginals = new WeakMap();
    const attrOriginals = new WeakMap();
    const listeners = [];
    const norm = (text) => text.replace(/\s+/g, ' ').trim();
    const translate = (text, lang) => (lang === 'en' && EN[norm(text)]) || null;

    const I18N = {
        lang: 'de',
        locale() {
            return this.lang === 'en' ? 'en-GB' : 'de-DE';
        },
        msg(key) {
            return MESSAGES[key][this.lang];
        },
        say(element, key) {
            element.dataset.msg = key || '';
            element.textContent = key ? this.msg(key) : '';
        },
        onChange(callback) {
            listeners.push(callback);
        },
        option(value) {
            return translate(value, this.lang) || value.trim();
        },
        setLang(lang) {
            this.lang = lang === 'en' ? 'en' : 'de';
            try {
                localStorage.setItem('lang', this.lang);
            } catch (error) { /* storage unavailable */ }
            document.documentElement.lang = this.lang;
            this.apply();
            listeners.forEach((callback) => callback(this.lang));
        },
        apply() {
            const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
            for (let node = walker.nextNode(); node; node = walker.nextNode()) {
                const parent = node.parentElement;
                if (!parent || parent.closest(SKIP) || parent.closest('script,style')) continue;
                if (!textOriginals.has(node)) textOriginals.set(node, node.nodeValue);
                const original = textOriginals.get(node);
                const translated = translate(original, this.lang);
                if (translated) {
                    const [, lead, trail] = original.match(/^(\s*)[\s\S]*?(\s*)$/);
                    node.nodeValue = lead + translated + trail;
                } else {
                    node.nodeValue = original;
                }
            }

            document.querySelectorAll(ATTRS.map((attr) => `[${attr}]`).join(',') + ',meta[name="description"]').forEach((element) => {
                if (element.closest(SKIP) || element.closest('.lang-switch')) return;
                const saved = attrOriginals.get(element) || {};
                const names = element.matches('meta') ? ['content'] : ATTRS;
                names.forEach((attr) => {
                    if (!element.hasAttribute(attr)) return;
                    if (!(attr in saved)) saved[attr] = element.getAttribute(attr);
                    element.setAttribute(attr, translate(saved[attr], this.lang) || saved[attr]);
                });
                attrOriginals.set(element, saved);
            });

            if (!this.titleOriginal) this.titleOriginal = document.title;
            document.title = translate(this.titleOriginal, this.lang) || this.titleOriginal;

            document.querySelectorAll('[data-msg]').forEach((element) => {
                if (element.dataset.msg) element.textContent = this.msg(element.dataset.msg);
            });
            document.querySelectorAll('.lang-switch button').forEach((button) => {
                button.setAttribute('aria-pressed', String(button.dataset.lang === this.lang));
            });
        }
    };

    document.querySelectorAll('.lang-switch button').forEach((button) => {
        button.addEventListener('click', () => I18N.setLang(button.dataset.lang));
    });

    window.I18N = I18N;
